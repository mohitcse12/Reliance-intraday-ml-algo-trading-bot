import os
import joblib
import numpy as np
import pandas as pd
import lightgbm as lgb
import optuna
from sklearn.model_selection import train_test_split
from sklearn.metrics import accuracy_score, classification_report

def load_and_preprocess_data(filepath):
    """
    Load historical OHLCV data for Reliance and generate technical features.
    """
    # Example CSV format expected: Timestamp, Open, High, Low, Close, Volume
    df = pd.read_csv(filepath)
    
    # Feature Engineering (Technical Indicators)
    df['Returns'] = df['Close'].pct_change()
    df['SMA_10'] = df['Close'].rolling(window=10).mean()
    df['SMA_50'] = df['Close'].rolling(window=50).mean()
    df['Volatility'] = df['Returns'].rolling(window=10).std()
    
    # Target Variable: 1 if next candle close is higher, else 0
    df['Target'] = np.where(df['Close'].shift(-1) > df['Close'], 1, 0)
    
    # Drop NaN values generated by rolling/shifting
    df.dropna(inplace=True)
    
    features = ['Open', 'High', 'Low', 'Close', 'Volume', 'Returns', 'SMA_10', 'SMA_50', 'Volatility']
    X = df[features]
    y = df['Target']
    
    return train_test_split(X, y, test_size=0.2, shuffle=False)

def objective(trial, X_train, y_train, X_val, y_val):
    """
    Optuna objective function to find best LightGBM hyperparameters.
    """
    params = {
        'objective': 'binary',
        'metric': 'binary_logloss',
        'boosting_type': 'gbdt',
        'n_estimators': trial.suggest_int('n_estimators', 50, 300),
        'learning_rate': trial.suggest_float('learning_rate', 0.01, 0.2, log=True),
        'max_depth': trial.suggest_int('max_depth', 3, 10),
        'num_leaves': trial.suggest_int('num_leaves', 20, 100),
        'random_state': 42,
        'verbose': -1
    }
    
    model = lgb.LGBMClassifier(**params)
    model.fit(X_train, y_train)
    
    preds = model.predict(X_val)
    accuracy = accuracy_score(y_val, preds)
    return accuracy

def main():
    print("Loading data and engineering features...")
    # Replace with your actual historical data CSV path
    data_path = 'data/reliance_historical_data.csv'
    
    try:
        X_train, X_val, y_train, y_val = load_and_preprocess_data(data_path)
    except FileNotFoundError:
        print(f"Data file not found at {data_path}. Please place your CSV file in a 'data/' folder.")
        return

    print("Running Optuna hyperparameter optimization...")
    study = optuna.create_study(direction='maximize')
    study.optimize(lambda trial: objective(trial, X_train, y_train, X_val, y_val), n_trials=20)
    
    print(f"Best Hyperparameters: {study.best_params}")
    
    # Train final model with best parameters
    best_params = study.best_params
    best_params['objective'] = 'binary'
    best_params['metric'] = 'binary_logloss'
    best_params['boosting_type'] = 'gbdt'
    best_params['random_state'] = 42
    
    final_model = lgb.LGBMClassifier(**best_params)
    final_model.fit(X_train, y_train)
    
    # Evaluate
    predictions = final_model.predict(X_val)
    print("Model Evaluation on Validation Set:")
    print(classification_report(y_val, predictions))
    
    # Save the trained model
    os.makedirs('models', exist_ok=True)
    model_path = 'models/reliance_lgbm_model.pkl'
    joblib.dump(final_model, model_path)
    print(f"Trained LightGBM model successfully saved to {model_path}")

if __name__ == "__main__":
    main()
